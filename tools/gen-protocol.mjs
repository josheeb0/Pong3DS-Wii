#!/usr/bin/env node
/**
 * Generates the TypeScript and C codecs from shared/protocol.json.
 *
 * A binary protocol spoken by three codebases rots the moment one side's byte
 * offsets drift from another's. Generating both sides from one spec makes that
 * failure impossible rather than merely unlikely.
 *
 *   node tools/gen-protocol.mjs
 *
 * Outputs (all committed; `make verify` fails if they differ from a fresh run):
 *   shared/gen/protocol.ts          TypeScript codec (server + web)
 *   3ds/source/net/pong_proto.h     C codec header
 *   3ds/source/net/pong_proto.c     C codec implementation
 *   shared/gen/golden.json          canonical byte vectors, one per message
 *   3ds/test/golden_data.h          the same vectors, for the host C test
 */

import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const spec = JSON.parse(readFileSync(join(ROOT, 'shared/protocol.json'), 'utf8'));

const SIZES = { u8: 1, i8: 1, u16: 2, i16: 2, u32: 4, i32: 4 };
const C_TYPES = { u8: 'uint8_t', i8: 'int8_t', u16: 'uint16_t', i16: 'int16_t', u32: 'uint32_t', i32: 'int32_t' };
const TS_GET = { u8: 'getUint8', i8: 'getInt8', u16: 'getUint16', i16: 'getInt16', u32: 'getUint32', i32: 'getInt32' };
const TS_SET = { u8: 'setUint8', i8: 'setInt8', u16: 'setUint16', i16: 'setInt16', u32: 'setUint32', i32: 'setInt32' };

const HDR = spec.header.bytes;
const fieldSize = (f) => (f.type === 'bytes' ? f.len : SIZES[f.type]);
const payloadSize = (m) => m.fields.reduce((a, f) => a + fieldSize(f), 0);
const snake = (s) => s.replace(/([a-z0-9])([A-Z])/g, '$1_$2').toLowerCase();
const banner = (cmt) => `${cmt} GENERATED BY tools/gen-protocol.mjs FROM shared/protocol.json -- DO NOT EDIT.`;

/* ------------------------------------------------------------------ layout */
// Offsets are computed once, here, and shared by both emitters. That is the
// single place a byte offset exists; neither language gets to invent its own.
const layout = new Map();
for (const m of spec.messages) {
  let off = 0;
  const fields = m.fields.map((f) => {
    const entry = { ...f, off, size: fieldSize(f) };
    off += entry.size;
    return entry;
  });
  layout.set(m.name, { fields, size: off });
}

/* ================================================================ TypeScript */
function emitTS() {
  const L = [];
  L.push(banner('//'), '');
  L.push('/* eslint-disable */', '');

  L.push('export const PROTOCOL_VERSION = ' + spec.protocolVersion + ';');
  L.push('export const HEADER_BYTES = ' + HDR + ';');
  L.push('export const MAGIC0 = ' + spec.header.magic0 + '; // ' + String.fromCharCode(spec.header.magic0));
  L.push('export const MAGIC1 = ' + spec.header.magic1 + '; // ' + String.fromCharCode(spec.header.magic1));
  L.push('');

  L.push('export const C = {');
  for (const [k, v] of Object.entries(spec.constants)) L.push(`  ${k}: ${v},`);
  L.push('} as const;', '');

  // Derived Q4 helpers — every consumer needs these and they must agree with C.
  L.push('export const Q4 = C.Q4_SHIFT;');
  L.push('export const toQ4 = (px: number): number => Math.round(px * (1 << Q4));');
  L.push('export const fromQ4 = (q: number): number => q / (1 << Q4);');
  L.push('export const FIELD_W_Q4 = C.FIELD_W << C.Q4_SHIFT;');
  L.push('export const FIELD_H_Q4 = C.FIELD_H << C.Q4_SHIFT;');
  L.push('');

  for (const [name, vals] of Object.entries(spec.enums)) {
    L.push(`export const ${name} = {`);
    for (const [k, v] of Object.entries(vals)) L.push(`  ${k}: ${v},`);
    L.push('} as const;');
    L.push(`export type ${name} = typeof ${name}[keyof typeof ${name}];`);
    L.push(`export const ${name}Name: Record<number, string> = {`);
    for (const [k, v] of Object.entries(vals)) L.push(`  ${v}: ${JSON.stringify(k)},`);
    L.push('};', '');
  }

  L.push('export const MsgType = {');
  for (const m of spec.messages) L.push(`  ${m.name}: ${m.id},`);
  L.push('} as const;');
  L.push('export type MsgType = typeof MsgType[keyof typeof MsgType];', '');

  L.push('export const MSG_NAME: Record<number, string> = {');
  for (const m of spec.messages) L.push(`  ${m.id}: ${JSON.stringify(m.name)},`);
  L.push('};', '');

  L.push('export const PAYLOAD_BYTES: Record<number, number> = {');
  for (const m of spec.messages) L.push(`  ${m.id}: ${layout.get(m.name).size},`);
  L.push('};', '');

  // Interfaces
  for (const m of spec.messages) {
    const { fields } = layout.get(m.name);
    L.push(`export interface ${m.name} {`);
    for (const f of fields) {
      L.push(`  ${f.name}: ${f.type === 'bytes' ? 'Uint8Array' : 'number'};`);
    }
    L.push('}', '');
  }

  // Header writer
  L.push('function writeHeader(dv: DataView, type: number, len: number, seq: number): void {');
  L.push('  dv.setUint8(0, MAGIC0);');
  L.push('  dv.setUint8(1, MAGIC1);');
  L.push('  dv.setUint8(2, PROTOCOL_VERSION);');
  L.push('  dv.setUint8(3, type);');
  L.push('  dv.setUint16(4, len, true);');
  L.push('  dv.setUint16(6, seq, true);');
  L.push('}', '');

  // Encoders / decoders
  for (const m of spec.messages) {
    const { fields, size } = layout.get(m.name);

    const argDecl = fields.length === 0 ? `_m: ${m.name} | undefined` : `m: ${m.name}`;
    L.push(`export function encode${m.name}(${argDecl}, seq = 0): Uint8Array<ArrayBuffer> {`);
    L.push(`  const buf = new Uint8Array(${HDR + size});`);
    L.push('  const dv = new DataView(buf.buffer);');
    L.push(`  writeHeader(dv, ${m.id}, ${size}, seq);`);
    for (const f of fields) {
      const at = HDR + f.off;
      if (f.type === 'bytes') {
        L.push(`  buf.set(m.${f.name}.subarray(0, ${f.len}), ${at});`);
      } else if (f.size === 1) {
        L.push(`  dv.${TS_SET[f.type]}(${at}, m.${f.name});`);
      } else {
        L.push(`  dv.${TS_SET[f.type]}(${at}, m.${f.name}, true);`);
      }
    }
    L.push('  return buf;');
    L.push('}', '');

    if (fields.length === 0) {
      L.push(`export function decode${m.name}(_buf: Uint8Array, _payloadOff: number): ${m.name} {`);
      L.push('  return {};');
      L.push('}', '');
      continue;
    }
    L.push(`export function decode${m.name}(buf: Uint8Array, payloadOff: number): ${m.name} {`);
    L.push('  const dv = new DataView(buf.buffer, buf.byteOffset, buf.byteLength);');
    L.push('  return {');
    for (const f of fields) {
      if (f.type === 'bytes') {
        L.push(`    ${f.name}: buf.subarray(payloadOff + ${f.off}, payloadOff + ${f.off + f.len}),`);
      } else if (f.size === 1) {
        L.push(`    ${f.name}: dv.${TS_GET[f.type]}(payloadOff + ${f.off}),`);
      } else {
        L.push(`    ${f.name}: dv.${TS_GET[f.type]}(payloadOff + ${f.off}, true),`);
      }
    }
    L.push('  };');
    L.push('}', '');
  }

  // Frame walker — the piece that makes one protocol work on every transport.
  L.push('export interface Frame {');
  L.push('  type: number;');
  L.push('  seq: number;');
  L.push('  payloadOff: number;');
  L.push('  payloadLen: number;');
  L.push('  buf: Uint8Array;');
  L.push('}', '');

  L.push('export const enum ParseError {');
  L.push('  OK = 0,');
  L.push('  BAD_MAGIC = 1,');
  L.push('  BAD_VERSION = 2,');
  L.push('  BAD_LENGTH = 3,');
  L.push('}', '');

  L.push('export interface ParseResult {');
  L.push('  frames: Frame[];');
  L.push('  consumed: number;');
  L.push('  error: ParseError;');
  L.push('}', '');

  L.push('/**');
  L.push(' * Walks a byte buffer and pops every complete frame.');
  L.push(' *');
  L.push(' * Identical for a TCP stream, a WebSocket binary message, an HTTP body and a');
  L.push(' * decoded SSE line: each is just bytes that happen to contain N frames. The');
  L.push(' * caller keeps any trailing partial frame (`consumed` says how much was used).');
  L.push(' */');
  L.push('export function parseFrames(buf: Uint8Array): ParseResult {');
  L.push('  const frames: Frame[] = [];');
  L.push('  const dv = new DataView(buf.buffer, buf.byteOffset, buf.byteLength);');
  L.push('  let off = 0;');
  L.push('  while (buf.length - off >= HEADER_BYTES) {');
  L.push('    if (dv.getUint8(off) !== MAGIC0 || dv.getUint8(off + 1) !== MAGIC1) {');
  L.push('      return { frames, consumed: off, error: ParseError.BAD_MAGIC };');
  L.push('    }');
  L.push('    if (dv.getUint8(off + 2) !== PROTOCOL_VERSION) {');
  L.push('      return { frames, consumed: off, error: ParseError.BAD_VERSION };');
  L.push('    }');
  L.push('    const type = dv.getUint8(off + 3);');
  L.push('    const len = dv.getUint16(off + 4, true);');
  L.push('    const seq = dv.getUint16(off + 6, true);');
  L.push('    if (len > C.MAX_FRAME_BYTES) {');
  L.push('      return { frames, consumed: off, error: ParseError.BAD_LENGTH };');
  L.push('    }');
  L.push('    const expected = PAYLOAD_BYTES[type];');
  L.push('    if (expected !== undefined && len !== expected) {');
  L.push('      return { frames, consumed: off, error: ParseError.BAD_LENGTH };');
  L.push('    }');
  L.push('    if (buf.length - off - HEADER_BYTES < len) break; // partial tail, wait for more');
  L.push('    frames.push({ type, seq, payloadOff: off + HEADER_BYTES, payloadLen: len, buf });');
  L.push('    off += HEADER_BYTES + len;');
  L.push('  }');
  L.push('  return { frames, consumed: off, error: ParseError.OK };');
  L.push('}', '');

  L.push('/** Concatenates encoded frames into one buffer (an HTTP body, a WS message). */');
  L.push('export function concatFrames(frames: Uint8Array[]): Uint8Array<ArrayBuffer> {');
  L.push('  let n = 0;');
  L.push('  for (const f of frames) n += f.length;');
  L.push('  const out = new Uint8Array(n);');
  L.push('  let o = 0;');
  L.push('  for (const f of frames) { out.set(f, o); o += f.length; }');
  L.push('  return out;');
  L.push('}', '');

  L.push('/** Fixed-width name/room fields are NUL-padded ASCII. */');
  L.push('export function padBytes(s: string, len: number): Uint8Array<ArrayBuffer> {');
  L.push('  const out = new Uint8Array(len);');
  L.push('  const enc = new TextEncoder().encode(s);');
  L.push('  out.set(enc.subarray(0, len));');
  L.push('  return out;');
  L.push('}', '');

  L.push('export function unpadBytes(b: Uint8Array): string {');
  L.push('  let end = b.length;');
  L.push('  while (end > 0 && b[end - 1] === 0) end--;');
  L.push('  return new TextDecoder().decode(b.subarray(0, end));');
  L.push('}', '');

  return L.join('\n');
}

/* ========================================================================= C */
function emitCHeader() {
  const L = [];
  L.push(banner('/*') + ' */');
  L.push('#ifndef PONG_PROTO_H');
  L.push('#define PONG_PROTO_H');
  L.push('');
  L.push('/*');
  L.push(' * Pure C99. Deliberately includes NO libctru headers -- this file is compiled');
  L.push(' * unchanged by the host test (clang) and by a future Wii client (devkitPPC).');
  L.push(' * Keeping it platform-free is what makes those reuses possible.');
  L.push(' *');
  L.push(' * All access is by explicit byte offset with memcpy into locals. Never cast a');
  L.push(' * byte buffer to a struct: ARM11 alignment and padding rules would silently');
  L.push(' * disagree with the wire layout.');
  L.push(' */');
  L.push('');
  L.push('#include <stdint.h>');
  L.push('#include <stdbool.h>');
  L.push('#include <stddef.h>');
  L.push('');
  L.push('#ifdef __cplusplus');
  L.push('extern "C" {');
  L.push('#endif');
  L.push('');

  L.push(`#define PONG_PROTOCOL_VERSION ${spec.protocolVersion}`);
  L.push(`#define PONG_HEADER_BYTES ${HDR}`);
  L.push(`#define PONG_MAGIC0 ${spec.header.magic0}`);
  L.push(`#define PONG_MAGIC1 ${spec.header.magic1}`);
  L.push('');

  for (const [k, v] of Object.entries(spec.constants)) {
    L.push(`#define PONG_${k} ${v}`);
  }
  L.push('');
  L.push('#define PONG_FIELD_W_Q4 (PONG_FIELD_W << PONG_Q4_SHIFT)');
  L.push('#define PONG_FIELD_H_Q4 (PONG_FIELD_H << PONG_Q4_SHIFT)');
  L.push('');
  L.push('/* Q4 -> 3DS top-screen pixels: /16 for fixed point, /2 for the 800x480 -> 400x240');
  L.push(' * mapping. One shift, no floats, no rounding drift. */');
  L.push('#define PONG_Q4_TO_TOPSCREEN(q) ((q) >> (PONG_Q4_SHIFT + 1))');
  L.push('');

  for (const [name, vals] of Object.entries(spec.enums)) {
    L.push(`typedef enum {`);
    for (const [k, v] of Object.entries(vals)) {
      L.push(`    PONG_${snake(name).toUpperCase()}_${k} = ${v},`);
    }
    L.push(`} Pong${name};`);
    L.push('');
  }

  L.push('typedef enum {');
  for (const m of spec.messages) L.push(`    PONG_MSG_${m.name} = ${m.id},`);
  L.push('} PongMsgType;');
  L.push('');

  for (const m of spec.messages) {
    const { fields, size } = layout.get(m.name);
    L.push(`#define PONG_${m.name}_BYTES ${size}`);
    L.push(`typedef struct {`);
    if (fields.length === 0) L.push('    uint8_t _empty; /* no fields */');
    for (const f of fields) {
      if (f.type === 'bytes') L.push(`    uint8_t ${snake(f.name)}[${f.len}];`);
      else L.push(`    ${C_TYPES[f.type]} ${snake(f.name)};`);
    }
    L.push(`} Pong${m.name};`);
    L.push('');
  }

  L.push('/* ------------------------------------------------------------ framing */');
  L.push('');
  L.push('typedef struct {');
  L.push('    uint8_t  type;');
  L.push('    uint16_t seq;');
  L.push('    uint16_t length;');
  L.push('    const uint8_t *payload;');
  L.push('} PongFrame;');
  L.push('');
  L.push('typedef enum {');
  L.push('    PONG_PARSE_OK = 0,');
  L.push('    PONG_PARSE_NEED_MORE = 1,  /* partial frame at tail; keep buffering */');
  L.push('    PONG_PARSE_BAD_MAGIC = 2,');
  L.push('    PONG_PARSE_BAD_VERSION = 3,');
  L.push('    PONG_PARSE_BAD_LENGTH = 4,');
  L.push('} PongParseResult;');
  L.push('');
  L.push('/* Pops one frame from `buf`. On PONG_PARSE_OK, *consumed is the frame size. */');
  L.push('PongParseResult pong_parse_frame(const uint8_t *buf, size_t len,');
  L.push('                                 PongFrame *out, size_t *consumed);');
  L.push('');
  L.push('/* Expected payload size for a type, or -1 if the type is unknown. */');
  L.push('int pong_payload_bytes(uint8_t type);');
  L.push('');
  L.push('/* NUL-pad an ASCII string into a fixed-width field. */');
  L.push('void pong_pad_bytes(uint8_t *dst, size_t dstlen, const char *src);');
  L.push('');

  for (const m of spec.messages) {
    const { size } = layout.get(m.name);
    L.push(`/* ${m.name} (${m.dir}) -- ${HDR + size} bytes framed */`);
    L.push(`size_t pong_write_${snake(m.name)}(uint8_t *out, size_t cap, uint16_t seq, const Pong${m.name} *m);`);
    L.push(`bool   pong_read_${snake(m.name)}(const uint8_t *p, uint16_t len, Pong${m.name} *out);`);
    L.push('');
  }

  L.push('#ifdef __cplusplus');
  L.push('}');
  L.push('#endif');
  L.push('');
  L.push('#endif /* PONG_PROTO_H */');
  return L.join('\n');
}

function emitCSource() {
  const L = [];
  L.push(banner('/*') + ' */');
  L.push('');
  L.push('#include "pong_proto.h"');
  L.push('#include <string.h>');
  L.push('');
  L.push('/* Little-endian accessors. ARM11 and x86 are both LE, so these compile to');
  L.push(' * plain loads on every target we care about, while staying correct anywhere. */');
  L.push('static inline void wr_u8(uint8_t *p, uint8_t v)   { p[0] = v; }');
  L.push('static inline void wr_u16(uint8_t *p, uint16_t v) { p[0] = (uint8_t)(v); p[1] = (uint8_t)(v >> 8); }');
  L.push('static inline void wr_u32(uint8_t *p, uint32_t v) { p[0] = (uint8_t)(v); p[1] = (uint8_t)(v >> 8); p[2] = (uint8_t)(v >> 16); p[3] = (uint8_t)(v >> 24); }');
  L.push('static inline uint8_t  rd_u8(const uint8_t *p)  { return p[0]; }');
  L.push('static inline uint16_t rd_u16(const uint8_t *p) { return (uint16_t)(p[0] | (p[1] << 8)); }');
  L.push('static inline uint32_t rd_u32(const uint8_t *p) { return (uint32_t)p[0] | ((uint32_t)p[1] << 8) | ((uint32_t)p[2] << 16) | ((uint32_t)p[3] << 24); }');
  L.push('');
  L.push('static void wr_header(uint8_t *p, uint8_t type, uint16_t len, uint16_t seq) {');
  L.push('    p[0] = PONG_MAGIC0;');
  L.push('    p[1] = PONG_MAGIC1;');
  L.push('    p[2] = PONG_PROTOCOL_VERSION;');
  L.push('    p[3] = type;');
  L.push('    wr_u16(p + 4, len);');
  L.push('    wr_u16(p + 6, seq);');
  L.push('}');
  L.push('');

  L.push('int pong_payload_bytes(uint8_t type) {');
  L.push('    switch (type) {');
  for (const m of spec.messages) {
    L.push(`    case PONG_MSG_${m.name}: return ${layout.get(m.name).size};`);
  }
  L.push('    default: return -1;');
  L.push('    }');
  L.push('}');
  L.push('');

  L.push('void pong_pad_bytes(uint8_t *dst, size_t dstlen, const char *src) {');
  L.push('    size_t i = 0;');
  L.push('    memset(dst, 0, dstlen);');
  L.push('    if (!src) return;');
  L.push('    for (; i < dstlen && src[i]; i++) dst[i] = (uint8_t)src[i];');
  L.push('}');
  L.push('');

  L.push('PongParseResult pong_parse_frame(const uint8_t *buf, size_t len,');
  L.push('                                 PongFrame *out, size_t *consumed) {');
  L.push('    uint16_t plen;');
  L.push('    int expected;');
  L.push('    if (len < PONG_HEADER_BYTES) return PONG_PARSE_NEED_MORE;');
  L.push('    if (buf[0] != PONG_MAGIC0 || buf[1] != PONG_MAGIC1) return PONG_PARSE_BAD_MAGIC;');
  L.push('    if (buf[2] != PONG_PROTOCOL_VERSION) return PONG_PARSE_BAD_VERSION;');
  L.push('    plen = rd_u16(buf + 4);');
  L.push('    if (plen > PONG_MAX_FRAME_BYTES) return PONG_PARSE_BAD_LENGTH;');
  L.push('    expected = pong_payload_bytes(buf[3]);');
  L.push('    if (expected >= 0 && (uint16_t)expected != plen) return PONG_PARSE_BAD_LENGTH;');
  L.push('    if (len < (size_t)PONG_HEADER_BYTES + plen) return PONG_PARSE_NEED_MORE;');
  L.push('    out->type = buf[3];');
  L.push('    out->length = plen;');
  L.push('    out->seq = rd_u16(buf + 6);');
  L.push('    out->payload = buf + PONG_HEADER_BYTES;');
  L.push('    *consumed = (size_t)PONG_HEADER_BYTES + plen;');
  L.push('    return PONG_PARSE_OK;');
  L.push('}');
  L.push('');

  for (const m of spec.messages) {
    const { fields, size } = layout.get(m.name);
    const sn = snake(m.name);

    L.push(`size_t pong_write_${sn}(uint8_t *out, size_t cap, uint16_t seq, const Pong${m.name} *m) {`);
    L.push(`    if (cap < ${HDR + size}) return 0;`);
    L.push(`    wr_header(out, PONG_MSG_${m.name}, ${size}, seq);`);
    if (fields.length === 0) L.push('    (void)m;');
    for (const f of fields) {
      const at = HDR + f.off;
      const nm = snake(f.name);
      if (f.type === 'bytes') L.push(`    memcpy(out + ${at}, m->${nm}, ${f.len});`);
      else if (f.size === 1) L.push(`    wr_u8(out + ${at}, (uint8_t)m->${nm});`);
      else if (f.size === 2) L.push(`    wr_u16(out + ${at}, (uint16_t)m->${nm});`);
      else L.push(`    wr_u32(out + ${at}, (uint32_t)m->${nm});`);
    }
    L.push(`    return ${HDR + size};`);
    L.push('}');
    L.push('');

    L.push(`bool pong_read_${sn}(const uint8_t *p, uint16_t len, Pong${m.name} *out) {`);
    L.push(`    if (len != ${size}) return false;`);
    if (fields.length === 0) { L.push('    (void)p; out->_empty = 0;'); }
    for (const f of fields) {
      const nm = snake(f.name);
      if (f.type === 'bytes') L.push(`    memcpy(out->${nm}, p + ${f.off}, ${f.len});`);
      else if (f.size === 1) L.push(`    out->${nm} = (${C_TYPES[f.type]})rd_u8(p + ${f.off});`);
      else if (f.size === 2) L.push(`    out->${nm} = (${C_TYPES[f.type]})rd_u16(p + ${f.off});`);
      else L.push(`    out->${nm} = (${C_TYPES[f.type]})rd_u32(p + ${f.off});`);
    }
    L.push('    return true;');
    L.push('}');
    L.push('');
  }

  return L.join('\n');
}

/* ============================================================ golden vectors */
// One canonical instance of every message, encoded by the TS side. The host C
// test decodes these exact bytes and asserts every field matches. This is what
// actually proves C and TypeScript agree, without 3DS hardware in the loop.
function goldenValue(f, i) {
  if (f.type === 'bytes') {
    return Array.from({ length: f.len }, (_, k) => (f.off + k * 7 + 1) & 0xff);
  }
  const signed = f.type[0] === 'i';
  const bits = SIZES[f.type] * 8;
  const raw = (f.off * 2654435761 + i * 40503 + 12345) >>> 0;
  if (signed) {
    const half = 1 << (bits - 1);
    return ((raw % (half * 2)) - half) | 0;
  }
  return raw % Math.pow(2, bits);
}

function emitGolden() {
  const vectors = [];
  spec.messages.forEach((m, i) => {
    const { fields, size } = layout.get(m.name);
    const buf = new Uint8Array(HDR + size);
    const dv = new DataView(buf.buffer);
    const seq = (i * 997) & 0xffff;
    dv.setUint8(0, spec.header.magic0);
    dv.setUint8(1, spec.header.magic1);
    dv.setUint8(2, spec.protocolVersion);
    dv.setUint8(3, m.id);
    dv.setUint16(4, size, true);
    dv.setUint16(6, seq, true);

    const values = {};
    for (const f of fields) {
      const v = goldenValue(f, i);
      values[f.name] = v;
      const at = HDR + f.off;
      if (f.type === 'bytes') buf.set(Uint8Array.from(v), at);
      else if (f.size === 1) dv[TS_SET[f.type]](at, v);
      else dv[TS_SET[f.type]](at, v, true);
    }
    vectors.push({ name: m.name, id: m.id, seq, payloadBytes: size, values, bytes: Array.from(buf) });
  });
  return vectors;
}

function emitGoldenC(vectors) {
  const L = [];
  L.push(banner('/*') + ' */');
  L.push('#ifndef PONG_GOLDEN_DATA_H');
  L.push('#define PONG_GOLDEN_DATA_H');
  L.push('');
  L.push('/*');
  L.push(' * Canonical frames produced by the TypeScript encoder, plus the exact field');
  L.push(' * values that produced them.');
  L.push(' *');
  L.push(' * The C codec decodes these bytes and every field is asserted against the');
  L.push(' * literal the TS side used. Asserting FIELDS rather than doing a C-only');
  L.push(' * encode/decode round-trip matters: a round-trip passes happily when read and');
  L.push(' * write share the same wrong offset. This does not.');
  L.push(' */');
  L.push('');
  L.push('#include <stdint.h>');
  L.push('#include <string.h>');
  L.push('#include "../source/net/pong_proto.h"');
  L.push('');
  L.push('#ifndef PONG_GOLDEN_FAIL');
  L.push('#include <stdio.h>');
  L.push('#define PONG_GOLDEN_FAIL(msg, field) \\');
  L.push('    do { printf("  FAIL %s.%s\\n", msg, field); return 1; } while (0)');
  L.push('#endif');
  L.push('');

  for (const v of vectors) {
    L.push(`static const uint8_t GOLDEN_${v.name}[${v.bytes.length}] = {`);
    for (let i = 0; i < v.bytes.length; i += 12) {
      L.push('    ' + v.bytes.slice(i, i + 12).map((b) => '0x' + b.toString(16).padStart(2, '0')).join(', ') + ',');
    }
    L.push('};');
  }
  L.push('');

  // One check function per message.
  for (const v of vectors) {
    const m = spec.messages.find((x) => x.name === v.name);
    const { fields } = layout.get(v.name);
    const sn = snake(v.name);
    L.push(`static int pong_golden_check_${sn}(void) {`);
    L.push('    PongFrame fr;');
    L.push('    size_t used = 0;');
    L.push(`    Pong${v.name} m;`);
    L.push(`    memset(&m, 0, sizeof m);`);
    L.push(`    if (pong_parse_frame(GOLDEN_${v.name}, sizeof GOLDEN_${v.name}, &fr, &used) != PONG_PARSE_OK)`);
    L.push(`        PONG_GOLDEN_FAIL("${v.name}", "<frame parse>");`);
    L.push(`    if (used != sizeof GOLDEN_${v.name}) PONG_GOLDEN_FAIL("${v.name}", "<consumed>");`);
    L.push(`    if (fr.type != PONG_MSG_${v.name}) PONG_GOLDEN_FAIL("${v.name}", "<type>");`);
    L.push(`    if (fr.seq != ${v.seq}) PONG_GOLDEN_FAIL("${v.name}", "<seq>");`);
    L.push(`    if (fr.length != ${v.payloadBytes}) PONG_GOLDEN_FAIL("${v.name}", "<length>");`);
    L.push(`    if (!pong_read_${sn}(fr.payload, fr.length, &m)) PONG_GOLDEN_FAIL("${v.name}", "<decode>");`);
    for (const f of fields) {
      const nm = snake(f.name);
      const val = v.values[f.name];
      if (f.type === 'bytes') {
        const lit = val.map((b) => '0x' + b.toString(16).padStart(2, '0')).join(', ');
        L.push(`    { static const uint8_t exp[${f.len}] = { ${lit} };`);
        L.push(`      if (memcmp(m.${nm}, exp, ${f.len}) != 0) PONG_GOLDEN_FAIL("${v.name}", "${f.name}"); }`);
      } else {
        L.push(`    if (m.${nm} != (${C_TYPES[f.type]})${val}) PONG_GOLDEN_FAIL("${v.name}", "${f.name}");`);
      }
    }
    // Re-encode and compare bytes, so the writer is covered too.
    L.push(`    { uint8_t back[${v.bytes.length}];`);
    L.push(`      size_t n = pong_write_${sn}(back, sizeof back, ${v.seq}, &m);`);
    L.push(`      if (n != sizeof back) PONG_GOLDEN_FAIL("${v.name}", "<encode size>");`);
    L.push(`      if (memcmp(back, GOLDEN_${v.name}, sizeof back) != 0) PONG_GOLDEN_FAIL("${v.name}", "<encode bytes>"); }`);
    L.push('    return 0;');
    L.push('}');
    L.push('');
  }

  L.push('static int pong_golden_check_all(void) {');
  L.push('    int rc = 0;');
  for (const v of vectors) {
    L.push(`    rc |= pong_golden_check_${snake(v.name)}();`);
  }
  L.push('    return rc;');
  L.push('}');
  L.push('');
  L.push(`#define PONG_GOLDEN_COUNT ${vectors.length}`);
  L.push('');
  L.push('#endif /* PONG_GOLDEN_DATA_H */');
  return L.join('\n');
}

/* ================================================================ trig table */
/*
 * Bounce angles need sin/cos, but Math.sin() in V8 and sinf() in newlib are not
 * guaranteed to produce identical bits. A shared integer table removes the
 * question entirely: the server and every client index the SAME numbers.
 *
 * 65 entries spanning 0..90 degrees, Q12 (4096 == 1.0).
 */
const TRIG_STEPS = 64;
function trigTables() {
  const sin = [], cos = [];
  for (let i = 0; i <= TRIG_STEPS; i++) {
    const a = (Math.PI / 2) * (i / TRIG_STEPS);
    sin.push(Math.round(Math.sin(a) * 4096));
    cos.push(Math.round(Math.cos(a) * 4096));
  }
  return { sin, cos };
}

function emitTrigTS() {
  const { sin, cos } = trigTables();
  const L = [];
  L.push(banner('//'), '');
  L.push('/* eslint-disable */', '');
  L.push('/** Quarter-wave sin/cos, Q12 (4096 = 1.0), 0..90 degrees in ' + TRIG_STEPS + ' steps. */');
  L.push(`export const TRIG_STEPS = ${TRIG_STEPS};`);
  L.push('export const SIN_Q12: readonly number[] = [');
  for (let i = 0; i < sin.length; i += 8) L.push('  ' + sin.slice(i, i + 8).join(', ') + ',');
  L.push('];');
  L.push('export const COS_Q12: readonly number[] = [');
  for (let i = 0; i < cos.length; i += 8) L.push('  ' + cos.slice(i, i + 8).join(', ') + ',');
  L.push('];');
  return L.join('\n');
}

function emitTrigC() {
  const { sin, cos } = trigTables();
  const L = [];
  L.push(banner('/*') + ' */');
  L.push('#ifndef PONG_TRIG_H');
  L.push('#define PONG_TRIG_H');
  L.push('#include <stdint.h>');
  L.push('');
  L.push('/* Quarter-wave sin/cos, Q12 (4096 = 1.0), 0..90 degrees in ' + TRIG_STEPS + ' steps.');
  L.push(' * Identical values to shared/gen/trig.ts so bounce angles cannot diverge');
  L.push(' * between the server and this client. */');
  L.push(`#define PONG_TRIG_STEPS ${TRIG_STEPS}`);
  L.push(`static const int16_t PONG_SIN_Q12[${sin.length}] = {`);
  for (let i = 0; i < sin.length; i += 8) L.push('    ' + sin.slice(i, i + 8).join(', ') + ',');
  L.push('};');
  L.push(`static const int16_t PONG_COS_Q12[${cos.length}] = {`);
  for (let i = 0; i < cos.length; i += 8) L.push('    ' + cos.slice(i, i + 8).join(', ') + ',');
  L.push('};');
  L.push('');
  L.push('#endif /* PONG_TRIG_H */');
  return L.join('\n');
}

/* ====================================================================== main */
function write(rel, content) {
  const abs = join(ROOT, rel);
  mkdirSync(dirname(abs), { recursive: true });
  writeFileSync(abs, content.endsWith('\n') ? content : content + '\n');
  console.log('  wrote ' + rel);
}

